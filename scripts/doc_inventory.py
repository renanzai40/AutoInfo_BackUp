def run_check() -> list[str]:
    """Check cross-doc consistency; return the list of human-readable failures."""
    failures: list[str] = []
    readme_text = read_text(README)
    agents_text = read_text(AGENTS)

    readme_values: dict[str, str | None] = {}
    for fact, pattern in FACTS:
        rv = extract_number(readme_text, pattern)
        av = extract_number(agents_text, pattern)
        match = rv is not None and rv == av
        rv_disp = rv if rv is not None else "not found"
        av_disp = av if av is not None else "not found"
        print(f"  {fact}: README.md={rv_disp}, AGENTS.md={av_disp} "
              f"-> {'match' if match else 'MISMATCH'}")
        readme_values[fact] = rv
        if not match:
            failures.append(f"fact '{fact}': README.md={rv_disp} vs AGENTS.md={av_disp}")

    skill_text = read_text(SKILL) if SKILL.exists() else ""
    for fact, pattern in SKILL_FACTS:
        rv = readme_values.get(fact)
        sv = extract_number(skill_text, pattern) if skill_text else None
        match = rv is not None and sv == rv
        rv_disp = rv if rv is not None else "not found"
        sv_disp = sv if sv is not None else "not found"
        print(f"  SKILL.md {fact}: README.md={rv_disp}, SKILL.md={sv_disp} "
              f"-> {'match' if match else 'MISMATCH'}")
        if not match:
            failures.append(
                f"doc-manager-skill '{fact}': SKILL.md={sv_disp} vs README.md={rv_disp} — "
                f"update .opencode/skills/doc-manager-skill/SKILL.md (§3 Step 3)"
            )

    stray = sorted(TESTS.glob("test_bug_*")) if TESTS.is_dir() else []
    if stray:
        names = ", ".join(p.name for p in stray)
        print(f"  Stray regression files: {names} -> FAIL")
        failures.append(f"tests/ contains {len(stray)} test_bug_* file(s): {names}")
    else:
        print("  Stray test_bug_* files in tests/: none -> ok")

    if OUT.exists():
        first = read_text(OUT).splitlines()[0] if read_text(OUT).splitlines() else ""
        header_ok = first.startswith("<!-- AUTO-GENERATED by scripts/doc_inventory.py")
        if header_ok:
            print("  docs/dev/doc-inventory.md: AUTO-GENERATED header present -> ok")
        else:
            print("  docs/dev/doc-inventory.md: AUTO-GENERATED header MISSING -> FAIL")
            failures.append("docs/dev/doc-inventory.md is stale: missing its AUTO-GENERATED header — regenerate with python3 scripts/doc_inventory.py")
    else:
        print("  docs/dev/doc-inventory.md: does not exist -> FAIL")
        failures.append("docs/dev/doc-inventory.md missing — run python3 scripts/doc_inventory.py first")

    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the AutoInfo documentation inventory (docs/dev/doc-inventory.md)."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify cross-doc consistency (README vs AGENTS facts, stray test_bug_* files, "
        "stale inventory header). No files are written. Exits 1 on any failure.",
    )
    args = parser.parse_args(argv)

    if args.check:
        print("doc_inventory --check")
        failures = run_check()
        print()
        if failures:
            print(f"check FAILED ({len(failures)} issue(s)):")
            for f in failures:
                print(f"  - {f}")
            return 1
        print("check passed: all facts match, no stray files, inventory fresh.")
        return 0

    rows = scan_docs()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render_report(rows), encoding="utf-8")
    total_lines = sum(r["lines"] for r in rows)
    print(f"Wrote {OUT} ({len(rows)} files, {total_lines} lines).")
    print(f"Regenerate after doc changes; verify with --check (exit 0 = clean).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
